import React, { useState } from 'react';
import { Language, TRANSLATIONS } from '../data/translations';
import {
  Link as LinkIcon,
  Copy,
  Check,
  X,
  Share2,
  ExternalLink,
  FileCode,
  FileText,
  Printer,
  Sparkles,
  Smartphone,
} from 'lucide-react';
import {
  downloadTextFile,
  printHtmlViaIframe,
  generateAdvisoryReportHtml,
  generateDiagnosisReportHtml,
  triggerBlobDownload,
} from '../utils/downloadUtils';

interface ExportLinkModalProps {
  language: Language;
  isOpen: boolean;
  onClose: () => void;
  exportUrl: string;
  title: string;
  cropName: string;
  questionOrSummary: string;
  fullContent: string;
  sources?: Array<{ title: string; uri: string }>;
  type: 'advisory' | 'diagnosis' | 'weather';
  onOpenExportView?: () => void;
}

export const ExportLinkModal: React.FC<ExportLinkModalProps> = ({
  language,
  isOpen,
  onClose,
  exportUrl,
  title,
  cropName,
  questionOrSummary,
  fullContent,
  sources,
  type,
  onOpenExportView,
}) => {
  const t = TRANSLATIONS[language];
  const [copied, setCopied] = useState<boolean>(false);

  const isTa = language === 'ta';
  const isTe = language === 'te';
  const isHi = language === 'hi';

  if (!isOpen) return null;

  const handleCopyLink = () => {
    navigator.clipboard.writeText(exportUrl);
    setCopied(true);
    setTimeout(() => setCopied(false), 2500);
  };

  const cleanSummary = questionOrSummary.length > 90 ? questionOrSummary.slice(0, 90) + '...' : questionOrSummary;

  // WhatsApp share URL with helpful message
  let whatsappText = `🌾 *BhuMitra AI Farming Advisory Report*\n\n*Crop:* ${cropName}\n*Query:* "${cleanSummary}"\n\nView and download the complete agricultural advice here:\n${exportUrl}`;
  if (isTa) {
    whatsappText = `🌾 *பூமித்ரா AI வேளாண் ஆலோசனை அறிக்கை*\n\n*பயிர்:* ${cropName}\n*கேள்வி:* "${cleanSummary}"\n\nமுழு அறிவியல் வழிகாட்டலை பார்க்க மற்றும் பதிவிறக்க இந்த இணைப்பைத் திறக்கவும்:\n${exportUrl}`;
  } else if (isTe) {
    whatsappText = `🌾 *భూమిత్ర AI వ్యవసాయ సలహా పత్రం*\n\n*పంట:* ${cropName}\n*ప్రశ్న:* "${cleanSummary}"\n\nపూర్తి శాస్త్రీయ వ్యవసాయ సలహాను చూడటానికి మరియు డౌన్‌లోడ్ చేసుకోవడానికి ఈ లింక్ తెరవండి:\n${exportUrl}`;
  } else if (isHi) {
    whatsappText = `🌾 *भूमिमित्र AI किसान परामर्श रिपोर्ट*\n\n*फसल:* ${cropName}\n*प्रश्न:* "${cleanSummary}"\n\nपूरी कृषि सलाह और वैज्ञानिक समाधान देखने व डाउनलोड करने के लिए यह लिंक खोलें:\n${exportUrl}`;
  }

  const whatsappUrl = `https://api.whatsapp.com/send?text=${encodeURIComponent(whatsappText)}`;

  // Email share URL
  let emailSubject = `BhuMitra AI Agriculture Advisory: ${cropName}`;
  if (isTa) {
    emailSubject = `பூமித்ரா AI வேளாண் அறிக்கை: ${cropName}`;
  } else if (isTe) {
    emailSubject = `భూమిత్ర AI వ్యవసాయ నివేదిక: ${cropName}`;
  } else if (isHi) {
    emailSubject = `भूमिमित्र AI किसान परामर्श रिपोर्ट: ${cropName}`;
  }
  const emailBody = `${whatsappText}\n\nGenerated by BhuMitra AI - Smart Crop Companion`;
  const emailUrl = `mailto:?subject=${encodeURIComponent(emailSubject)}&body=${encodeURIComponent(emailBody)}`;

  const handleQuickDownloadPdf = () => {
    if (type === 'advisory') {
      const html = generateAdvisoryReportHtml({
        cropName,
        question: questionOrSummary,
        answer: fullContent,
        sources,
        language,
      });
      const blob = new Blob([html], { type: 'text/html;charset=utf-8' });
      const filename = `BhuMitra_Export_${cropName.replace(/\s+/g, '_')}.html`;
      triggerBlobDownload(blob, filename);
    } else if (type === 'diagnosis') {
      const html = generateDiagnosisReportHtml({
        cropName,
        notes: questionOrSummary,
        report: fullContent,
        language,
      });
      const blob = new Blob([html], { type: 'text/html;charset=utf-8' });
      const filename = `BhuMitra_Prescription_${cropName.replace(/\s+/g, '_')}.html`;
      triggerBlobDownload(blob, filename);
    }
  };

  const getModalTitle = () => {
    if (isTa) return 'ஏற்றுமதி மற்றும் பகிர்வு இணைப்பு';
    if (isTe) return 'ఎగుమతి మరియు షేర్ లింక్';
    if (isHi) return 'शेयर एवं निर्यात लिंक';
    return 'Share & Export Link';
  };

  const getModalSubtitle = () => {
    if (isTa) return 'எவரும் இந்த இணைப்பைப் பயன்படுத்தி அறிக்கையை பார்க்கலாம்';
    if (isTe) return 'ఎవరైనా ఈ లింక్‌ని ఉపయోగించి నివేదికను చూడవచ్చు';
    if (isHi) return 'कोई भी इस लिंक का उपयोग करके रिपोर्ट देख सकता है';
    return 'Shareable permanent link for farmers & advisors';
  };

  const getLinkedReportLabel = () => {
    if (isTa) return 'இணைக்கப்பட்ட அறிக்கை';
    if (isTe) return 'జతచేసిన నివేదిక';
    if (isHi) return 'संलग्न रिपोर्ट';
    return 'Linked Report';
  };

  const getGeneratedLinkLabel = () => {
    if (isTa) return 'உருவாக்கப்பட்ட நேரடி இணைப்பு:';
    if (isTe) return 'రూపొందించిన డైరెక్ట్ లింక్:';
    if (isHi) return 'तैयार किया गया सीधा लिंक:';
    return 'Generated Export Link:';
  };

  const getCopyBtnText = () => {
    if (copied) {
      if (isTa) return 'நகலெடுக்கப்பட்டது';
      if (isTe) return 'కాపీ చేయబడింది';
      if (isHi) return 'कॉपी हो गया';
      return 'Copied';
    }
    if (isTa) return 'நகலெடு';
    if (isTe) return 'లింక్ కాపీ చేయండి';
    if (isHi) return 'कॉपी करें';
    return 'Copy Link';
  };

  const getChannelsTitle = () => {
    if (isTa) return 'உடனடி பகிர்வு தேர்வுகள்';
    if (isTe) return 'తక్షణ షేరింగ్ మార్గాలు';
    if (isHi) return 'त्वरित शेयर माध्यम';
    return 'Instant Share Channels';
  };

  const getWhatsappLabel = () => {
    if (isTa) return 'வாட்ஸ்அப் பகிர்வு';
    if (isTe) return 'వాట్సాప్‌లో షేర్';
    if (isHi) return 'व्हाट्सएप पर शेयर';
    return 'Share to WhatsApp';
  };

  const getEmailLabel = () => {
    if (isTa) return 'மின்னஞ்சல்';
    if (isTe) return 'ఈమెయిల్ ద్వారా షేర్';
    if (isHi) return 'ईमेल लिंक';
    return 'Email Link';
  };

  const getOpenViewLabel = () => {
    if (isTa) return 'ஏற்றுமதி பக்கத்தை திறக்க';
    if (isTe) return 'ఎగుమతి పేజీని తెరవండి';
    if (isHi) return 'निर्यात पेज खोलें';
    return 'Open Export View';
  };

  const getDownloadPdfLabel = () => {
    if (isTa) return 'PDF பதிவிறக்கு';
    if (isTe) return 'PDF నివేదిక డౌన్‌లోడ్';
    if (isHi) return 'PDF रिपोर्ट डाउनलोड';
    return 'Download PDF Report';
  };

  return (
    <div className="fixed inset-0 z-50 bg-stone-950/70 backdrop-blur-xs flex items-center justify-center p-3 sm:p-5 overflow-y-auto">
      <div className="bg-white rounded-3xl w-full max-w-lg shadow-2xl border border-stone-200 overflow-hidden animate-in fade-in zoom-in-95 duration-150">
        {/* Modal Header */}
        <div className="bg-gradient-to-r from-emerald-800 to-green-900 text-white p-5 flex items-center justify-between">
          <div className="flex items-center gap-3">
            <div className="w-10 h-10 rounded-xl bg-lime-400 text-emerald-950 flex items-center justify-center shadow-md">
              <LinkIcon className="w-5 h-5 stroke-[2.5]" />
            </div>
            <div>
              <h3 className="font-extrabold text-base sm:text-lg text-white">
                {getModalTitle()}
              </h3>
              <p className="text-xs text-emerald-200">
                {getModalSubtitle()}
              </p>
            </div>
          </div>
          <button
            onClick={onClose}
            className="p-2 rounded-xl bg-emerald-900/60 hover:bg-emerald-700 text-emerald-200 hover:text-white transition cursor-pointer"
            title="Close"
          >
            <X className="w-5 h-5" />
          </button>
        </div>

        {/* Modal Content */}
        <div className="p-5 sm:p-6 space-y-5 text-stone-900">
          {/* Summary Preview Box */}
          <div className="p-3.5 rounded-2xl bg-stone-50 border border-stone-200 text-xs">
            <div className="flex items-center justify-between text-stone-600 mb-1">
              <span className="font-bold text-emerald-800 uppercase tracking-wider text-[10px]">
                {getLinkedReportLabel()}
              </span>
              <span className="font-semibold text-stone-500">{cropName}</span>
            </div>
            <p className="font-bold text-stone-900 italic line-clamp-2">
              "{questionOrSummary}"
            </p>
          </div>

          {/* Generated URL Box */}
          <div>
            <label className="block text-xs font-bold text-stone-700 mb-1.5 flex items-center justify-between">
              <span>{getGeneratedLinkLabel()}</span>
              {copied && (
                <span className="text-emerald-700 text-xs font-semibold flex items-center gap-1">
                  <Check className="w-3.5 h-3.5" />
                  {t.copied}
                </span>
              )}
            </label>
            <div className="flex items-center gap-2">
              <input
                type="text"
                readOnly
                value={exportUrl}
                className="flex-1 px-3.5 py-2.5 bg-stone-100 border border-stone-300 rounded-xl text-xs font-mono text-stone-700 truncate select-all focus:outline-none focus:border-emerald-600"
              />
              <button
                type="button"
                onClick={handleCopyLink}
                className={`px-4 py-2.5 rounded-xl font-bold text-xs flex items-center gap-1.5 transition shrink-0 cursor-pointer shadow-xs ${
                  copied
                    ? 'bg-emerald-700 text-white'
                    : 'bg-emerald-600 hover:bg-emerald-700 text-white'
                }`}
              >
                {copied ? <Check className="w-4 h-4" /> : <Copy className="w-4 h-4" />}
                <span>{getCopyBtnText()}</span>
              </button>
            </div>
          </div>

          {/* Instant Share Options */}
          <div>
            <h5 className="text-xs font-bold uppercase tracking-wider text-stone-600 mb-2">
              {getChannelsTitle()}
            </h5>
            <div className="grid grid-cols-2 gap-2.5">
              {/* WhatsApp Button */}
              <a
                href={whatsappUrl}
                target="_blank"
                rel="noopener noreferrer"
                className="p-3 rounded-xl bg-green-50 hover:bg-green-100 border border-green-300 text-green-900 text-xs font-bold flex items-center justify-center gap-2 transition cursor-pointer shadow-2xs text-center"
              >
                <Smartphone className="w-4 h-4 text-green-700 shrink-0" />
                <span>{getWhatsappLabel()}</span>
              </a>

              {/* Email Button */}
              <a
                href={emailUrl}
                className="p-3 rounded-xl bg-blue-50 hover:bg-blue-100 border border-blue-300 text-blue-900 text-xs font-bold flex items-center justify-center gap-2 transition cursor-pointer shadow-2xs text-center"
              >
                <Share2 className="w-4 h-4 text-blue-700 shrink-0" />
                <span>{getEmailLabel()}</span>
              </a>
            </div>
          </div>

          {/* Direct Actions: Open Export View or Download */}
          <div className="pt-2 border-t border-stone-200 flex flex-col sm:flex-row items-center justify-between gap-2.5">
            {onOpenExportView && (
              <button
                type="button"
                onClick={() => {
                  onClose();
                  onOpenExportView();
                }}
                className="w-full sm:w-auto px-4 py-2 rounded-xl bg-stone-100 hover:bg-stone-200 text-stone-800 text-xs font-bold flex items-center justify-center gap-1.5 transition cursor-pointer"
              >
                <ExternalLink className="w-3.5 h-3.5 text-stone-600" />
                <span>{getOpenViewLabel()}</span>
              </button>
            )}

            <button
              type="button"
              onClick={handleQuickDownloadPdf}
              className="w-full sm:w-auto px-4 py-2 rounded-xl bg-emerald-50 hover:bg-emerald-100 border border-emerald-300 text-emerald-900 text-xs font-bold flex items-center justify-center gap-1.5 transition cursor-pointer"
            >
              <FileCode className="w-3.5 h-3.5 text-emerald-700" />
              <span>{getDownloadPdfLabel()}</span>
            </button>
          </div>
        </div>
      </div>
    </div>
  );
};
